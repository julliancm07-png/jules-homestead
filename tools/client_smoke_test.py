#!/usr/bin/env python3
"""Client smoke test: install the .mrpack like a launcher, launch the FULL client under Xvfb with Mesa software
OpenGL (llvmpipe) via portablemc (offline account), join a singleplayer world, screenshot, and check for crashes.

What a pass establishes: all client mods load together, mixins apply, the renderer initialises (Sodium etc. on
software GL), the integrated server starts with the pack (quests, configs), the player joins and the game keeps
ticking for --settle seconds without a crash. It does NOT establish GPU/shader behaviour, performance, input/keybinds,
or audio (no sound device in the cloud).

--scenario normal   : world generated by the headless server
--scenario blizzard : world spawn moved to a snowy biome and a severity-3 blizzard started before the client joins
--scenario showcase : spawn at a village, morning, frozen time, peaceful; runs tools/showcase.script through the
                      dev harness (-Dhomesteadcore.dev.script): panorama capture + UI screenshots, then quits
Usage: python3 -I tools/client_smoke_test.py [--scenario blizzard] [--settle 90] [--skip-install] [--update-panorama]
Requires: Xvfb, ImageMagick `import`, portablemc (pip), Java 25 at /opt/jdk25 (or HOMESTEAD_JAVA).
"""
import argparse
import glob
import os
import pathlib
import re
import shutil
import subprocess
import sys
import time

ROOT = pathlib.Path(__file__).resolve().parent.parent
INST = ROOT / "build" / "client-instance"
JAVA = os.environ.get("HOMESTEAD_JAVA", "/opt/jdk25/bin/java")
PY = [sys.executable, "-I"]


def server(*cmds, keep=False):
    args = PY + [str(ROOT / "tools" / "server_test.py"), "--timeout", "900", "--settle", "8"]
    if keep:
        args.append("--keep-world")
    for c in cmds:
        args += ["--cmd", c]
    subprocess.run(args, check=True, env={**os.environ, "JAVA_HOME": str(pathlib.Path(JAVA).parent.parent)})
    return (ROOT / "build" / "server-test" / "server-test.log").read_text()


def prepare_world(scenario):
    if scenario == "normal":
        server("difficulty peaceful")
    elif scenario == "showcase":
        log = server("locate structure #minecraft:village")
        m = re.search(r"nearest #minecraft:village \(([^)]*)\) is at \[(-?\d+), (?:~|-?\d+), (-?\d+)\]", log)
        if not m:
            raise SystemExit("could not locate a village")
        _, x, z = m.groups()
        server(f"forceload add {x} {z}",
               f"execute positioned {x} 0 {z} positioned over motion_blocking_no_leaves run setworldspawn ~ ~ ~",
               "gamerule spawn_radius 0", "time set 1000", "gamerule advance_time false", "gamerule advance_weather false",
               "weather clear", "difficulty peaceful", keep=True)
    else:
        log = server("locate biome minecraft:snowy_plains")
        m = re.search(r"nearest minecraft:snowy_plains is at \[(-?\d+), (?:~|-?\d+), (-?\d+)\]", log)
        if not m:
            raise SystemExit("could not locate snowy plains")
        x, z = m.groups()
        server(f"forceload add {x} {z}",
               f"execute positioned {x} 0 {z} positioned over motion_blocking_no_leaves run setworldspawn ~ ~ ~",
               "gamerule spawn_radius 0", "time set noon", "difficulty peaceful",
               "homestead weather start blizzard 1800 3", keep=True)
    saves = INST / "saves"
    shutil.rmtree(saves, ignore_errors=True)
    saves.mkdir(parents=True)
    shutil.copytree(ROOT / "build" / "server-test" / "world", saves / "HomesteadTest")
    (saves / "HomesteadTest" / "session.lock").unlink(missing_ok=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenario", default="normal", choices=["normal", "blizzard", "showcase", "title"])
    ap.add_argument("--settle", type=int, default=90)
    ap.add_argument("--skip-install", action="store_true")
    ap.add_argument("--script", help="showcase world + this dev-harness script instead of tools/showcase.script; "
                                     "screenshots go to build/debug-shots (diagnostics, never committed)")
    ap.add_argument("--update-panorama", action="store_true",
                    help="showcase: copy the captured title-screen panorama into resourcepacks/homestead-resources-src")
    a = ap.parse_args()
    mrpack = sorted((ROOT / "build" / "dist").glob("*.mrpack"))[-1]
    if not a.skip_install:
        subprocess.run(PY + [str(ROOT / "tools" / "mrpack_install.py"), str(mrpack), str(INST)], check=True)
    # Test instance only: skip MCA's first-join "destiny" screen so the screenshot shows the world.
    mca = INST / "config" / "mca.json"
    if mca.exists():
        import json
        cfg = json.loads(mca.read_text())
        cfg["launchIntoDestiny"] = False
        mca.write_text(json.dumps(cfg, indent=2))
    if a.scenario != "title":
        prepare_world(a.scenario)
    for d in ("logs", "crash-reports", "screenshots"):
        shutil.rmtree(INST / d, ignore_errors=True)
    xvfb = subprocess.Popen(["Xvfb", ":99", "-screen", "0", "1280x720x24"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(2)
    env = {**os.environ, "DISPLAY": ":99", "LIBGL_ALWAYS_SOFTWARE": "1", "MESA_GL_VERSION_OVERRIDE": "4.5", "MESA_GLSL_VERSION_OVERRIDE": "450"}
    cmd = ["portablemc", "--main-dir", str(ROOT / "build" / "pmc"), "start", "--mc-dir", str(INST), "fabric:26.1.2:0.20.1",
           "--jvm", JAVA, "--jvm-arg=-Xmx6G", "-u", "JulesTest", "--join-world", "HomesteadTest", "--resolution", "1280x720"]
    if a.scenario in ("showcase", "title"):
        script = pathlib.Path(a.script).resolve() if a.script else ROOT / "tools" / (a.scenario + ".script")
        cmd.insert(cmd.index("-u"), f"--jvm-arg=-Dhomesteadcore.dev.script={script}")
    if a.scenario == "title":
        i = cmd.index("--join-world")
        del cmd[i:i + 2]
    out = open(ROOT / "build" / "client-launcher.log", "w")
    if a.scenario in ("showcase", "title"):
        shutil.rmtree(INST / "screenshots", ignore_errors=True)
    p = subprocess.Popen(cmd, env=env, stdout=out, stderr=subprocess.STDOUT)
    latest = INST / "logs" / "latest.log"
    joined_at, start, result = None, time.time(), "TIMEOUT"
    try:
        while time.time() - start < 1500:
            text = latest.read_text(errors="replace") if latest.exists() else ""
            if glob.glob(str(INST / "crash-reports" / "*.txt")) or "Minecraft Crash Report" in text:
                result = "CRASH"
                break
            if p.poll() is not None:
                result = "PASS" if (a.scenario in ("showcase", "title") and "[dev] step done: quit" in text) else "EXITED"
                break
            if joined_at is None and "JulesTest joined the game" in text:
                joined_at = time.time()
            if joined_at and a.scenario not in ("showcase", "title") and time.time() - joined_at >= a.settle:
                shot = ROOT / "docs" / "screenshots" / f"client-smoke-{a.scenario}.png"
                shot.parent.mkdir(parents=True, exist_ok=True)
                subprocess.run(["import", "-window", "root", str(shot)], env=env, check=False)
                result = "PASS"
                break
            time.sleep(3)
    finally:
        p.terminate()
        try:
            p.wait(timeout=60)
        except subprocess.TimeoutExpired:
            p.kill()
        xvfb.terminate()
    text = latest.read_text(errors="replace") if latest.exists() else ""
    if a.scenario in ("showcase", "title"):
        shots = INST / "screenshots"
        dest = ROOT / "build" / "debug-shots" if a.script else ROOT / "docs" / "screenshots"
        dest.mkdir(parents=True, exist_ok=True)
        pano = ROOT / "resourcepacks" / "homestead-resources-src" / "panorama"
        for f in sorted(shots.glob("*.png")) if shots.exists() else []:
            if f.name.startswith("panorama_"):
                if not a.update_panorama:
                    continue  # keep the committed panorama unless explicitly asked (avoids image churn in git)
                pano.mkdir(parents=True, exist_ok=True)
                shutil.copy(f, pano / f.name)
            else:
                shutil.copy(f, dest / f.name)
            print("   captured", f.name)
    for pat in (r"Loading \d+ mods", r"OpenGL Renderer: .*", r"Loaded \d+ chapter groups.*", r"joined the game", r"Severe front started.*"):
        m = re.search(pat, text)
        if m:
            print("  ", m.group(0))
    crashes = glob.glob(str(INST / "crash-reports" / "*.txt"))
    for c in crashes:
        print("   crash report:", c)
        print("   ", "\n    ".join(pathlib.Path(c).read_text().splitlines()[:12]))
    print(f"client smoke test [{a.scenario}]: {result}" + (f" (in-world {a.settle}s)" if result == "PASS" else ""))
    sys.exit(0 if result == "PASS" else 1)


if __name__ == "__main__":
    main()
